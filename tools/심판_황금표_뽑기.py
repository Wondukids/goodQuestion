def _채점_한건(
    대사: str,
    모드: str,
    opening: str | None,
    closing: str | None,
    목표: str | None,
) -> dict:
    재료 = scoring.채점재료(
        대사=대사,
        response_mode=모드,
        character_opening=opening,
        character_closing=closing,
        scene_goal=목표,
        # 아래 둘은 규칙 심판 셋이 안 보는 값이라 고정해 둔다 (심판 검사는 TS 쪽에서 가짜 호출로 잰다).
        child_utterance="며느리가 불쌍해요",
        이야기_재료="며느리는 방귀를 며칠씩 참아 배가 빵빵하고 얼굴이 노랗게 변했다.",
    )
    결과 = [
        scoring.고정대사_지어냈나(재료),
        scoring.종료턴_생성했나(재료),
        scoring.장면목표_누출(재료),
    ]
    대사_뼈대 = scoring._뼈대(대사)
    return {
        "input": {
            "대사": 대사,
            "response_mode": 모드,
            "character_opening": opening,
            "character_closing": closing,
            "scene_goal": 목표,
        },
        "expected": {
            # 부속 순수 함수도 같이 잰다 — 여기가 갈리면 위 셋도 같이 갈린다.
            "skeleton": 대사_뼈대,
            "containsFixedLine": {
                # 고정 대사가 `None` 이면 물음 자체가 성립하지 않는다. 빈 문자열은 물어본다
                # (조각이 하나도 안 남아 `False` 가 나오는 갈래가 여기다).
                "opening": None
                if opening is None
                else scoring._고정대사가_들어있나(대사_뼈대, opening),
                "closing": None
                if closing is None
                else scoring._고정대사가_들어있나(대사_뼈대, closing),
            },
            "fabricatedFixedLine": _채점_적기(결과[0]),
            "closingGenerated": _채점_적기(결과[1]),
            "sceneGoalLeak": _채점_적기(결과[2]),
            "violationCount": scoring.위반_수(결과),
            "gradedCount": scoring.판정한_수(결과),
        },
    }


def _채점_적기(항목: scoring.채점) -> dict:
    return {"name": 항목.name, "value": 항목.value, "comment": 항목.comment}


