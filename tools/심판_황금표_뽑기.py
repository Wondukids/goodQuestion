def 뽑기() -> list[dict]:
    """축을 세 덩이로 나눠 곱한다. 한 덩이로 곱하면 표가 한쪽으로 쏠린다.

    고정 대사 축과 장면 목표 축은 **서로를 안 본다** (검사가 따로다). 그래서 둘을 다 곱하면
    같은 답이 늘어날 뿐이라, 한쪽을 고정하고 다른 쪽만 흔든다.
    """
    사례들: list[dict] = []
    본것: set[str] = set()

    def 더하기(대사들, 모드들, 고정쌍들, 목표들) -> None:
        조합 = itertools.product(대사들, 모드들, 고정쌍들, 목표들)
        for 대사, 모드, (opening, closing), 목표 in 조합:
            열쇠 = json.dumps([대사, 모드, opening, closing, 목표], ensure_ascii=False)
            if 열쇠 in 본것:
                continue
            본것.add(열쇠)
            사례 = _채점_한건(대사, 모드, opening, closing, 목표)
            사례들.append({"kind": "채점", "id": len(사례들), **사례})

    # ① 고정 대사 축 — 목표는 시드 값 하나로 고정하고 고정쌍을 다 흔든다.
    더하기(대사들, ["NORMAL", "CLOSING"], 고정쌍들, [장면_목표])
    # ② 장면 목표 축 — 고정쌍은 대화 장면 하나로 고정하고 목표를 다 흔든다.
    더하기(대사들, ["NORMAL"], [(첫_대사, 끝_대사)], 목표들)
    # ③ 모드 축 — `종료턴_생성했나` 는 `CLOSING` 인지 아닌지로만 갈리므로 축을 줄인다.
    #    다만 comment 에 모드 이름이 그대로 실려 나오므로 `GUIDED` 도 한 번 지난다.
    더하기(
        ["", "   \n\t ", "네 말을 들으니 마음이 가벼워졌어.", 첫_대사],
        모드들,
        [(첫_대사, 끝_대사), (None, None)],
        [장면_목표, None],
    )
    return 사례들


def JSON_뽑기(시작_id: int) -> list[dict]:
    return [
        {
            "kind": "JSON",
            "id": 시작_id + 자리,
            "input": {"응답": 응답},
            "expected": {"extractJson": scoring._JSON_뽑기(응답)},
        }
        for 자리, 응답 in enumerate(JSON_사례들)
    ]


