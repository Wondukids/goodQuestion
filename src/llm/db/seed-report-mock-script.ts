/** 대화 한 턴 — 아이가 말하고, 캐릭터가 받는다. */
export interface 턴대본 {
  /** 아이 발화 원문. 이것이 `messages.text` 가 되고 분석 LLM 에 그대로 간다. */
  아이: string
  /**
   * 그 발화를 받은 캐릭터의 **생성 대사**. 마지막 턴에는 없다 — 그 자리는 장면의
   * 고정 마지막 대사(`character_closing`)가 차지한다.
   */
  캐릭터?: string
}

/** 대화 장면 하나. 시작은 `character_opening`, 끝은 `character_closing` 이다. */
export interface 장면대본 {
  /** `story_scenes.code` — 대화 장면 넷 중 하나 (`sc_banggui_03·05·07·09`). */
  scene_code: string
  턴들: readonly 턴대본[]
  /** 중단한 활동은 마지막 고정 대사가 없다. 기본은 `false`(붙인다). */
  닫지_않음?: boolean
}

/** 미션 안 대화 하나 (`mission_messages`). 본 대화와 표가 다르다. */
export interface 미션대본 {
  /** `story_missions.code` — 지금은 `ms_banggui_pear` 하나만 쓴다. */
  mission_code: string
  /** 미션이 끼어든 대화 장면. `story_missions.scene_id` 와 같아야 한다. */
  scene_code: string
  /**
   * 아이가 탭으로 고른 소품의 id (`config.items[].id` — `sokuri`·`bojagi`·`byeotjip`).
   * 말이 아닌 입력이라 `mission_sessions.selections` 에 남는다 (명세 6절 · 미션 명세 M4).
   */
  소품: string
  단계들: readonly { step: string; 물음: string; 아이: string }[]
  /** 미션을 닫는 캐릭터 대사 (`config.closing`). */
  마무리: string
}

/** 활동(세션) 한 건. */
export interface 활동대본 {
  /** 그 아이의 **몇 번째** 활동인가. 1부터. `story_sessions` 정렬과 id 에 쓴다. */
  차례: number
  status: 'completed' | 'stopped'
  /** 시작 시각. **정해진 값이다** — 다시 돌려도 같은 값이어야 리포트가 안 흔들린다. */
  시작: string
  /** 활동 길이(분). `completed_at` 은 `시작 + 이 값`이다. */
  걸린_분: number
  장면들: readonly 장면대본[]
  미션?: 미션대본
}

/** 아이 한 명. */
export interface 아이대본 {
  /** 1~10. id 를 만드는 번호이자 명세 10절 표의 행 번호다. */
  번호: number
  /** 표식(`[리포트목]`)이 **붙지 않은** 이름. 표식은 넣는 쪽이 붙인다. */
  이름: string
  출생연도: number
  /** `children.character_id` — 온보딩 프리셋 12종 중 하나 (`src/lib/characters.ts`). */
  캐릭터: string
  /** 이 아이를 심는 이유. 명세 10절 「무엇을 보려고」 칸이다. */
  메모: string
  활동들: readonly 활동대본[]
}

